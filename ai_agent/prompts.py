"""
提示词配置模块

所有 LLM 提示词模板集中管理，支持自定义覆盖。使用方式：

    from ai_agent.prompts import PromptsConfig
    config = AgentConfig(prompts=PromptsConfig(system_prompt="自定义提示词..."))
"""

from dataclasses import dataclass, field


@dataclass
class PromptsConfig:
    """Agent 所有提示词模板的集中配置"""

    # ============================================================
    # 系统提示词
    # ============================================================

    system_prompt: str = (
        "你是一个智能 AI Agent，能够通过工具调用和规划来完成复杂任务。\n"
        "请用中文回复用户。\n"
        "完成所有步骤后，基于工具执行结果生成完整、有帮助的总结。"
    )

    # ============================================================
    # 复杂度验证（Planner）
    # ============================================================

    verify_complexity_system: str = (
        "你是一个任务复杂度判断专家。用户的请求是一个多步骤任务，需要规划执行？\n"
        '如果请求满足以下任意条件请回答「是」，否则回答「否」：\n'
        "1. 需要调用多个不同的工具才能完成\n"
        "2. 需要按照先后顺序执行多个步骤\n"
        "3. 涉及搜索信息、处理结果、保存输出等多个阶段\n"
        "4. 需要批量处理多个文件或数据\n\n"
        '请只回答「是」或「否」。'
    )
    verify_complexity_user: str = "请判断以下请求是否需要规划：\n{user_input}"

    # ============================================================
    # 计划生成（Planner）
    # ============================================================

    plan_system: str = (
        "你是一个任务规划专家。请将用户的请求分解为具体的执行步骤。\n"
        "{tools_description}"
        "{skills_section}"
        "请输出 JSON 格式的计划，每个步骤包含以下字段：\n"
        "- id: 步骤编号（从1开始）\n"
        "- description: 步骤描述\n"
        "- tool_hint: 建议使用的工具名（可选）\n"
        "- dependencies: 依赖的步骤 id 列表（如 [1] 表示依赖第1步完成，[] 表示无依赖）\n"
        "- skill: 如果某个可用技能的描述与任务高度匹配，可以在此字段填写技能名称"
        "，该技能的内容将被加载用于指导执行（可选）\n\n"
        '格式：{{"steps": [{{"id": 1, "description": "...", "tool_hint": "tool_name",'
        ' "dependencies": [], "skill": "技能名(可选)"}}, ...]}}\n'
        "要求：\n"
        "1. 步骤应该具体、可执行，每个步骤完成一件事\n"
        "2. 步骤总数不超过 10 个\n"
        "3. tool_hint 是可选的，仅当明显需要特定工具时给出\n"
        "4. dependencies 是关键：明确标注每个步骤的依赖关系\n"
        "5. 互不依赖的步骤可以标记为空依赖 []，表示可以并行执行\n"
        "6. 仅输出 JSON，不要有其他内容"
    )
    plan_user: str = "请为以下任务制定执行计划：\n{task}"

    # ============================================================
    # 重新规划（Planner）
    # ============================================================

    replan_system: str = (
        "你是一个任务规划专家。当前计划执行遇到问题，请根据反馈调整计划。\n"
        "请输出调整后的 JSON 格式计划，仅输出 JSON。"
    )
    replan_user: str = (
        "原始计划：\n{original_plan}\n\n"
        "执行反馈：{feedback}\n\n"
        "请输出调整后的计划："
    )

    # ============================================================
    # 工具调用格式说明（Agent._build_messages）
    # ============================================================

    tool_call_format_section: str = "\n## 工具调用格式\n"

    tool_call_format_with_plan: str = (
        "请使用以下 JSON 格式调用工具（仅输出 JSON，不要附带文本）：\n"
        '{{"tool_call": {{"name": "工具名", "arguments": {{"参数": "值"}}}}}}'
    )

    tool_call_format_no_plan: str = (
        "当你需要调用工具时，请使用以下 JSON 格式：\n"
        '{{"tool_call": {{"name": "工具名", "arguments": {{"参数": "值"}}}}}}\n'
        "如果不需要调用工具，直接回复用户即可。"
    )

    # ============================================================
    # 计划执行提示（Agent._build_messages）
    # ============================================================

    plan_header: str = "\n## 当前任务计划\n{plan_text}"

    plan_executable_single: str = (
        "\n**⚠️ 你正在执行计划，现在必须完成 Step {step_id}: {step_desc}**"
    )

    plan_executable_multi: str = (
        "\n**⚡ 当前有 {count} 个步骤可以并行执行: {descs}**\n"
        "你可以一次调用多个互不依赖的工具来加速执行。"
    )

    plan_must_call_tools: str = (
        "\n**你必须通过调用工具来完成计划中的每一步。不要跳过步骤，不要直接回复文本。**"
    )

    plan_json_only: str = "\n请**只输出**工具调用 JSON，不要附带任何解释文字。"

    # ============================================================
    # 未调用工具提醒（Agent.run）
    # ============================================================

    no_toolcall_hint: str = (
        "⚠️ 计划尚未完成！你必须继续执行。\n"
        "进度：{completed}/{total}\n"
        "立即执行：{step_hint}\n"
        "请只输出工具调用 JSON：\n"
        '{{"tool_call": {{"name": "工具名", "arguments": {{"参数": "值"}}}}}}'
    )

    # ============================================================
    # 自动重新规划通知（Agent.run）
    # ============================================================

    replan_notification: str = (
        "[系统通知] 检测到计划执行中有步骤失败，已自动重新规划。\n"
        "新计划共 {total_steps} 个步骤。\n"
        "已完成: {completed}, 待执行: {remaining}"
    )

    # ============================================================
    # 计划工具描述注入（Agent._build_messages）
    # ============================================================

    tools_section_header: str = "\n## 可用工具\n"

    # ============================================================
    # 总结提示词（Agent._build_summary_prompt）
    # ============================================================

    summary_system: str = "所有计划步骤已完成。请根据工具执行结果，生成一个清晰、完整的总结回复。"

    summary_user: str = (
        "用户原始请求: {task}\n\n"
        "已完成步骤:\n{steps}\n\n"
        "请总结回复用户。"
    )

    summary_with_failures: str = (
        "\n注意：有 {failed_count} 个步骤执行失败。"
        "请在总结中说明哪些步骤已完成、哪些失败，并给出建议。"
    )

    # ============================================================
    # 强制总结（Agent._force_summary）
    # ============================================================

    force_summary_system: str = "请根据已获得的信息，给用户一个简洁的总结回复。"

    force_summary_user: str = "请总结当前任务的进展情况。"

    force_summary_fallback: str = "任务已达到最大执行轮次，部分步骤可能未完成。"

    force_summary_fallback_retry: str = "任务已达到最大执行轮次，部分步骤可能未完成。请尝试简化请求后重试。"

    # ============================================================
    # 工具调用轮数上限提示
    # ============================================================

    tool_rounds_exceeded_log: str = "工具调用轮数已达上限 ({max_rounds})，强制结束本轮并生成总结"

    # ============================================================
    # 回退消息
    # ============================================================

    fallback_empty_answer: str = (
        "抱歉，我暂时无法完成你的请求。"
        "请尝试简化问题或重新表述后重试。"
    )

    fallback_exception: str = "抱歉，处理过程中遇到问题，请重新尝试。"

    fallback_llm_error: str = "抱歉，LLM 调用失败: {error}"

    fallback_unavailable: str = "抱歉，暂时无法处理你的请求。"

    fallback_interrupted: str = "任务已被用户中断。"

    # ============================================================
    # use_skill 工具响应
    # ============================================================

    skill_not_found: str = "未找到技能 '{skill_name}'。\n可用技能: {available}"

    # ============================================================
    # 错误收集（Agent._collect_failed_steps_info）
    # ============================================================

    failed_steps_header: str = "以下步骤执行失败，需要调整计划："

    failed_step_line: str = (
        "- Step {step_id}: {description}\n"
        "  错误类型: {error_cat}\n"
        "  错误详情: {result}"
    )

    completed_steps_header: str = "\n已完成的步骤："

    completed_step_line: str = "- Step {step_id}: {description} [已完成]"

    # ============================================================
    # 计划格式化（Plan.format_for_prompt）
    # ============================================================

    plan_title: str = "执行计划（任务: {task}）:"

    plan_step_status_icons: dict = field(default_factory=lambda: {
        "pending": "⏳",
        "in_progress": "🔄",
        "completed": "✅",
        "failed": "❌",
        "skipped": "⏭️",
    })

    plan_deps_format: str = " [依赖: {deps}]"

    plan_step_format: str = "  {icon} Step {step_id}: {desc}{deps}"

    plan_step_result: str = "      结果: {result}"

    plan_parallel_hint: str = "\n⚡ 当前可并行执行 ({count} 步): {descs}"

    plan_current_step: str = "\n当前应执行: Step {step_id} - {desc}"

    # ============================================================
    # 计划无步骤回退
    # ============================================================

    plan_no_failed_steps: str = "无失败步骤"
